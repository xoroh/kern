/**
 * Docs-shell chrome: admonitions and persisted tabs (the Docusaurus-patterned
 * additions, ported as shared components).
 *
 * ADR-STYLE RULES
 * - Admonition: a callout band with a semantic role per intent. Content
 *   pages compose it; no page draws its own warning box (one visual, one
 *   a11y treatment).
 * - PlatformTabs: the web/RN switcher. Today the two platforms are separate
 *   pages linked by `meta.nativePeer`; this component makes the switch a
 *   first-class control AND persists the reader's platform choice
 *   (localStorage) so the next visit lands on the platform they read last.
 *   The variant MEANING is frozen per platform (`docs/platform-parity.md`) —
 *   this control navigates, it never relabels.
 */

import { cn } from "@xoroh/kern";
import type { ReactNode } from "react";
import { T_BODY_SM, T_LABEL_LG } from "../systems/type-scale";

/* ------------------------------------------------------------- Admonition */

export type AdmonitionIntent = "note" | "tip" | "warning" | "danger";

/**
 * v2: an admonition is a TONAL CALLOUT — one container expression (the
 * intent's container fill, no stroke, no colored left band). The old form
 * paired a colored `border-l-4` with a 40%-tinted fill: two expressions on
 * one card, and the left band is not an M3 pattern. Label and body ink come
 * from the matching on-container role so contrast is generated by the
 * theme, not asserted here.
 */
const INTENT_STYLE: Record<
  AdmonitionIntent,
  { band: string; ink: string; label: string }
> = {
  note: {
    band: "bg-(--sys-color-surface-container-low)",
    ink: "text-(--sys-color-on-surface)",
    label: "Note",
  },
  tip: {
    band: "bg-(--sys-color-info-container)",
    ink: "text-(--sys-color-on-info-container)",
    label: "Tip",
  },
  warning: {
    band: "bg-(--sys-color-warning-container)",
    ink: "text-(--sys-color-on-warning-container)",
    label: "Warning",
  },
  danger: {
    band: "bg-(--sys-color-error-container)",
    ink: "text-(--sys-color-on-error-container)",
    label: "Danger",
  },
};

export function Admonition({
  intent = "note",
  title,
  children,
}: {
  intent?: AdmonitionIntent;
  /** Overrides the per-intent default label. */
  title?: string;
  children: ReactNode;
}) {
  const style = INTENT_STYLE[intent];
  return (
    <aside
      // The band is a complementary note, not a form control: `aside` with a
      // label is the native semantic, no ARIA role needed.
      aria-label={title ?? style.label}
      className={cn(
        "flex flex-col gap-2 rounded-(--sys-shape-corner-large-increased) px-5 py-4",
        style.band,
      )}
    >
      <p className={`m-0 ${T_LABEL_LG} ${style.ink}`}>{title ?? style.label}</p>
      <div className={`m-0 ${T_BODY_SM} ${style.ink}`}>{children}</div>
    </aside>
  );
}

/* ------------------------------------------------------------ PlatformTabs */

export type PlatformTab = {
  id: string;
  label: string;
  href: string;
};

const PLATFORM_STORAGE_KEY = "kern.platform-tabs.v1";

/** The reader's last platform choice, or null. SSR-safe. */
export function loadPlatformChoice(): string | null {
  try {
    if (typeof localStorage === "undefined") return null;
    return localStorage.getItem(PLATFORM_STORAGE_KEY);
  } catch {
    return null;
  }
}

export function savePlatformChoice(id: string): void {
  try {
    if (typeof localStorage === "undefined") return;
    localStorage.setItem(PLATFORM_STORAGE_KEY, id);
  } catch {
    // A preference that cannot persist is still a usable preference.
  }
}

/**
 * Persisted platform tabs (web/RN switcher).
 *
 * `tabs` is the domain's pair (or set); `active` is the one showing. Picking
 * a tab remembers it (`loadPlatformChoice` reads it back) and navigates via
 * plain anchors — the hrefs are real routes, so the switch works without
 * JavaScript and crawlers see both pages.
 */
export function PlatformTabs({
  tabs,
  active,
  label = "Platform",
  onPick,
}: {
  tabs: PlatformTab[];
  active: string;
  label?: string;
  /** Extra side effect on pick (the navigation itself is the anchor's). */
  onPick?: (id: string) => void;
}) {
  return (
    <nav aria-label={label} className="flex flex-wrap items-center gap-2">
      {tabs.map((tab) => {
        const isActive = tab.id === active;
        return (
          <a
            key={tab.id}
            href={tab.href}
            aria-current={isActive ? "page" : undefined}
            onClick={() => {
              savePlatformChoice(tab.id);
              onPick?.(tab.id);
            }}
            className={cn(
              "inline-flex min-h-12 items-center rounded-(--sys-shape-corner-full) px-5 py-2 no-underline",
              T_LABEL_LG,
              isActive
                ? "bg-(--sys-color-primary-container) text-(--sys-color-on-primary-container)"
                : "bg-(--sys-color-surface-container-low) text-(--sys-color-on-surface-variant)",
            )}
          >
            {tab.label}
          </a>
        );
      })}
    </nav>
  );
}

/* ----------------------------------------------------------- Breadcrumbs */

export type Crumb = {
  label: string;
  /** Absent on the last crumb — the page you are on is not a link. */
  href?: string;
};

/**
 * The breadcrumb trail. Domain-injected crumbs, one shared treatment: the
 * foundations pages and the component catalog show the same shape, so a
 * reader always knows where in the docs tree they are.
 */
export function Breadcrumbs({
  items,
  label = "Breadcrumb",
}: {
  items: Crumb[];
  label?: string;
}) {
  return (
    <nav
      aria-label={label}
      className={`flex flex-wrap items-center gap-2 ${T_BODY_SM} text-(--sys-color-on-surface-variant)`}
    >
      {items.map((crumb) => {
        const last = crumb.href === undefined;
        return (
          <span
            key={crumb.href ?? `current-${crumb.label}`}
            className="flex items-center gap-2"
          >
            {crumb.href && !last ? (
              <a
                href={crumb.href}
                className="text-(--sys-color-on-surface-variant) no-underline hover:underline"
              >
                {crumb.label}
              </a>
            ) : (
              <span className="text-(--sys-color-on-surface)">
                {crumb.label}
              </span>
            )}
            {last ? null : <span aria-hidden="true">/</span>}
          </span>
        );
      })}
    </nav>
  );
}

/* ------------------------------------------------------------- Pagination */

export type PageLink = { href: string; title: string };

/**
 * Generalised prev/next pagination. The foundations shell and the component
 * footer both navigate a domain-ordered list; this is the one treatment —
 * the target's TITLE rides beside its href so the reader knows where the
 * link goes before taking it.
 */
export function Pagination({
  prev,
  next,
  label = "Pages",
}: {
  prev?: PageLink;
  next?: PageLink;
  label?: string;
}) {
  return (
    <nav
      aria-label={label}
      className="flex items-stretch justify-between gap-4 border-t border-(--sys-color-outline-variant) pt-6"
    >
      {prev ? (
        <a
          href={prev.href}
          className="flex-1 rounded-(--sys-shape-corner-extra-large) bg-(--sys-color-surface-container-low) p-5 text-(--sys-color-on-surface) no-underline hover:bg-(--sys-color-on-surface)/8 active:bg-(--sys-color-on-surface)/12"
        >
          <span className={T_BODY_SM}>← Previous</span>
          <span className="block">{prev.title}</span>
        </a>
      ) : (
        <span className="flex-1" />
      )}
      {next ? (
        <a
          href={next.href}
          className="flex-1 rounded-(--sys-shape-corner-extra-large) bg-(--sys-color-surface-container-low) p-5 text-right text-(--sys-color-on-surface) no-underline hover:bg-(--sys-color-on-surface)/8 active:bg-(--sys-color-on-surface)/12"
        >
          <span className={T_BODY_SM}>Next →</span>
          <span className="block">{next.title}</span>
        </a>
      ) : (
        <span className="flex-1" />
      )}
    </nav>
  );
}
