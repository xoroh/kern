/**
 * The 400-weight canvas every committed shape is drawn on — the same
 * constant `<Icon>` paints (`ICON_VIEW_BOX` in `@xoroh/kern-icons`).
 */
const VIEW_BOX = "0 0 24 24";

export type ChromeIconProps = Omit<
  SVGProps<SVGSVGElement>,
  "width" | "height" | "viewBox" | "fill" | "children" | "color"
> & {
  /** Which chrome glyph to paint. Closed set — full catalog lives in `<Icon>`. */
  readonly name: ChromeIconName;
  /** FILL 1 (filled) vs FILL 0 (outline). Defaults to outline. */
  readonly filled?: boolean;
  /** Rendered edge length in px. Defaults to 24, matching `<Icon>`. */
  readonly size?: number;
  /** Paint colour. Defaults to `currentColor`, matching `<Icon>`. */
  readonly color?: string;
  /**
   * Accessible name. When omitted the icon is decorative and hidden from
   * assistive technology — the same contract `<Icon>` keeps.
   */
  readonly title?: string;
  /** Test hook, rendered as `data-testid`. */
  readonly testID?: string;
};

/**
 * One inline `<svg><path>`, SSR-safe, no registry import.
 *
 * Markup mirrors `<Icon>`: same viewBox, same fill rule (nonzero — none of
 * the chrome glyphs ships an evenodd path), same width/height derivation,
 * same decorative-unless-titled semantics. A filled glyph without filled
 * path data falls back to its outline, the same rule `getIconShape` applies.
 */
export function ChromeIcon({
  name,
  filled,
  size = 24,
  color = "currentColor",
  title,
  testID,
  ...rest
}: ChromeIconProps) {
  const shape = PATHS[name];
  const d = filled ? (shape.f ?? shape.o) : shape.o;
  return (
    <svg
      width={size}
      height={size}
      viewBox={VIEW_BOX}
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      role={title ? "img" : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      data-testid={testID}
      {...rest}
    >
      <path d={d} fill={color} fillRule="nonzero" clipRule="nonzero" />
    </svg>
  );
}

/** Resolve one chrome glyph to paint-ready values without rendering. */
export function getChromeIconShape(
  name: ChromeIconName,
  options: { filled?: boolean } = {},
): { d: string; fillRule: "nonzero" } {
  const shape = PATHS[name];
  return {
    d: options.filled ? (shape.f ?? shape.o) : shape.o,
    fillRule: "nonzero",
  };
}
