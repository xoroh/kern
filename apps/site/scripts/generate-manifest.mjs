// Regenerates src/generated/manifest.ts from the repo-level docs/components.md.
//
// The manifest is the site's route source of truth: it is parsed out of the
// generated inventory, never hand-listed, so a new component file in
// packages/ produces a new site page with no site edit. Run from apps/site:
//   bun run generate
//
// Reads (outside apps/site, read-only):  ../../docs/components.md
// Writes (inside apps/site):              src/generated/manifest.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");
const DOCS = join(APP, "..", "..", "docs", "components.md");

/** Section heading in components.md -> the platform slug the site routes on. */
const PLATFORMS = {
  Web: "web",
  Native: "mobile",
};

const source = readFileSync(DOCS, "utf8");

const entries = [];
for (const block of source.split(/^## /m).slice(1)) {
  const heading = block.slice(0, block.indexOf("\n")).trim();
  const platform = PLATFORMS[heading.replace(/\s*\(.*\)$/, "")];
  if (!platform) {
    // A section we do not route on (theme, tokens) is skipped, not an error,
    // so adding a non-component section upstream cannot break the site build.
    continue;
  }
  for (const row of block.matchAll(
    /^\| `([^`]+)` \| `([^`]+)` \| (real|stub) \|$/gm,
  )) {
    entries.push({
      name: row[1],
      export: row[2],
      platform,
      status: row[3],
    });
  }
}

// A slug is unique per platform; web and mobile can share a component name
// (Button exists on both), so the route key is the platform-qualified slug.
//
// This collapse is a BACKSTOP, not the mechanism. Two source files exporting
// the same symbol for the same platform was a real state until 2026-10-03 —
// `Split` was defined in both `packages/kern/src/components/split.tsx` and
// `packages/kern/src/start/panes.tsx` — and it was resolved by RULING (the grid
// recipe became `SplitGrid`), not by hiding a row. The upstream generator
// (`packages/mcp/scripts/generate-manifest.mjs`) now dedups on `platform/name`
// and FAILS on two different exports claiming one slug, so a collision should
// never reach this file. Keep the collapse anyway: it is cheap, and the failure
// mode it protects against is a manifest that invents a second `web/split`
// route which cannot exist.
//
// The collision is PRINTED, not swallowed: same-name drift between two
// generators is drift someone has to reconcile.
const bySlug = new Map();
const collisions = [];
for (const entry of entries) {
  const key = `${entry.platform}/${entry.name}`;
  const existing = bySlug.get(key);
  if (existing === undefined) {
    bySlug.set(key, entry);
    continue;
  }
  if (existing.export === entry.export) {
    collisions.push(
      `${key}: \`${entry.export}\` is exported from two source files — collapsed to one registry row`,
    );
    continue;
  }
  throw new Error(
    `duplicate manifest slug ${key} — \`${existing.export}\` and \`${entry.export}\` are different exports fighting over one route`,
  );
}
if (collisions.length > 0) {
  console.log(
    `generate-manifest: ${collisions.length} same-export slug collision(s) collapsed (should not happen — the upstream generator now fails on this; see .team/reports/kern-split-ruling.md):`,
  );
  for (const c of collisions) console.log(`  ${c}`);
}

const deduped = [...bySlug.values()];
const byPlatform = { web: [], mobile: [] };
for (const entry of deduped) byPlatform[entry.platform].push(entry);
for (const list of Object.values(byPlatform)) {
  list.sort((a, b) => a.name.localeCompare(b.name));
}

const PLATFORM_KEYS = Object.keys(byPlatform);

// Canonical registry counts (T2 P0-counts): parsed from `parity/contract.ts`
// (`PARITY_COUNTS`), never hard-coded here. Read as text with a regex — the
// same style `scripts/check-parity.mjs` uses — so this script runs under both
// bun and node with no TypeScript loader. A missing or unparsable export is a
// loud failure, not a silent zero: counts nobody verified are worse than none.
const CONTRACT_SRC = readFileSync(
  join(APP, "..", "..", "parity", "contract.ts"),
  "utf8",
);
const countsMatch = CONTRACT_SRC.match(
  /export const PARITY_COUNTS\s*=\s*\{\s*web:\s*(\d+),\s*native:\s*(\d+),\s*shared:\s*(\d+)\s*\}/,
);
if (!countsMatch) {
  console.error(
    "generate-manifest: PARITY_COUNTS not found in parity/contract.ts — refusing to emit counts nobody verified",
  );
  process.exit(1);
}
const PARITY_COUNTS = {
  web: Number(countsMatch[1]),
  native: Number(countsMatch[2]),
  shared: Number(countsMatch[3]),
};

const toEntry = (platform) => (c) => ({
  slug: `${platform}/${c.name}`,
  name: c.name,
  export: c.export,
  platform,
  status: c.status,
});

const all = []
  .concat(byPlatform.web.map(toEntry("web")))
  .concat(byPlatform.mobile.map(toEntry("mobile")));

const out = `// GENERATED by scripts/generate-manifest.mjs - do not hand-edit.
// Source: docs/components.md (generated by packages/mcp/scripts/generate-manifest.mjs).

export type Platform = ${JSON.stringify(PLATFORM_KEYS)}[number];
export type ComponentStatus = "real" | "stub";

export type ComponentEntry = {
  /** platform-qualified route slug, e.g. "web/button" */
  slug: string;
  /** URL path segment, e.g. "button" */
  name: string;
  /** exported symbol, e.g. "Button" */
  export: string;
  platform: Platform;
  status: ComponentStatus;
};

export const COMPONENTS: ComponentEntry[] = ${JSON.stringify(all, null, 2)};

export const COMPONENT_COUNT = COMPONENTS.length;

/**
 * Canonical registry counts, emitted from PARITY_COUNTS in
 * parity/contract.ts (see the parse above) — the site never hard-codes
 * its own copy. "web" / "native" are registry rows, "shared" is concepts;
 * different units, do not compare them.
 */
export const PARITY_COUNTS = ${JSON.stringify(PARITY_COUNTS, null, 2)};

const BY_SLUG = new Map(COMPONENTS.map((c) => [c.slug, c]));

export function getComponent(slug: string): ComponentEntry | undefined {
  return BY_SLUG.get(slug);
}

export function componentsOn(platform: Platform): ComponentEntry[] {
  return COMPONENTS.filter((c) => c.platform === platform);
}
`;

const target = join(APP, "src", "generated", "manifest.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, "utf8");

// The output is a TRACKED, generated file (S2 co-sign ruling: "from a tracked
// input -> track it"), so whatever this script writes must already satisfy the
// repo formatter. Emitting unformatted code meant every `bun run generate` left
// `apps/site/src/generated/manifest.ts` dirty, which fails `bun run lint` in CI
// on a fresh checkout — the kind of gate failure that looks like someone broke
// something when nobody did. Format here, at the source, rather than relying on
// someone to remember to run `format` after generating.
try {
  const { execFileSync } = await import("node:child_process");
  execFileSync("npx", ["biome", "check", "--write", target], {
    stdio: "ignore",
  });
} catch {
  // Formatter unavailable (offline / no npx). The file is still written and
  // correct; only its formatting is not guaranteed, and `bun run lint` will say so.
  console.warn(
    "generate-manifest: could not run biome; run `bun run format` before lint",
  );
}

console.log(
  "generate-manifest: " +
    deduped.length +
    " rows (web " +
    byPlatform.web.length +
    ", mobile " +
    byPlatform.mobile.length +
    ") -> " +
    target,
);
