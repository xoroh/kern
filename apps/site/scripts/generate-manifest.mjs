// Regenerates src/generated/manifest.ts from the repo-level docs/components.md.
//
// The manifest is the site's route source of truth: it is parsed out of the
// generated inventory, never hand-listed, so a new component file in
// packages/ produces a new site page with no site edit. Run from apps/site:
//   bun run generate
//
// Reads (outside apps/site, read-only):  ../../docs/components.md
// Writes (inside apps/site):              src/generated/manifest.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");
const DOCS = join(APP, "..", "..", "docs", "components.md");

/** Section heading in components.md -> the platform slug the site routes on. */
const PLATFORMS = {
  Web: "web",
  Native: "mobile",
};

const source = readFileSync(DOCS, "utf8");

const entries = [];
for (const block of source.split(/^## /m).slice(1)) {
  const heading = block.slice(0, block.indexOf("\n")).trim();
  const platform = PLATFORMS[heading.replace(/\s*\(.*\)$/, "")];
  if (!platform) {
    // A section we do not route on (theme, tokens) is skipped, not an error,
    // so adding a non-component section upstream cannot break the site build.
    continue;
  }
  for (const row of block.matchAll(
    /^\| `([^`]+)` \| `([^`]+)` \| (real|stub) \|$/gm,
  )) {
    entries.push({
      name: row[1],
      export: row[2],
      platform,
      status: row[3],
    });
  }
}

const byPlatform = { web: [], mobile: [] };
for (const entry of entries) byPlatform[entry.platform].push(entry);
for (const list of Object.values(byPlatform)) {
  list.sort((a, b) => a.name.localeCompare(b.name));
}

// A slug is unique per platform; web and mobile can share a component name
// (Button exists on both), so the route key is the platform-qualified slug.
const seen = new Set();
for (const entry of entries) {
  const key = `${entry.platform}/${entry.name}`;
  if (seen.has(key)) {
    throw new Error(
      `duplicate manifest slug ${key} - components.md and the site would disagree`,
    );
  }
  seen.add(key);
}

const PLATFORM_KEYS = Object.keys(byPlatform);

const toEntry = (platform) => (c) => ({
  slug: `${platform}/${c.name}`,
  name: c.name,
  export: c.export,
  platform,
  status: c.status,
});

const all = []
  .concat(byPlatform.web.map(toEntry("web")))
  .concat(byPlatform.mobile.map(toEntry("mobile")));

const out = `// GENERATED by scripts/generate-manifest.mjs - do not hand-edit.
// Source: docs/components.md (generated by packages/mcp/scripts/generate-manifest.mjs).

export type Platform = ${JSON.stringify(PLATFORM_KEYS)}[number];
export type ComponentStatus = "real" | "stub";

export type ComponentEntry = {
  /** platform-qualified route slug, e.g. "web/button" */
  slug: string;
  /** URL path segment, e.g. "button" */
  name: string;
  /** exported symbol, e.g. "Button" */
  export: string;
  platform: Platform;
  status: ComponentStatus;
};

export const COMPONENTS: ComponentEntry[] = ${JSON.stringify(all, null, 2)};

export const COMPONENT_COUNT = COMPONENTS.length;

const BY_SLUG = new Map(COMPONENTS.map((c) => [c.slug, c]));

export function getComponent(slug: string): ComponentEntry | undefined {
  return BY_SLUG.get(slug);
}

export function componentsOn(platform: Platform): ComponentEntry[] {
  return COMPONENTS.filter((c) => c.platform === platform);
}
`;

const target = join(APP, "src", "generated", "manifest.ts");
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out, "utf8");

// The output is a TRACKED, generated file (S2 co-sign ruling: "from a tracked
// input -> track it"), so whatever this script writes must already satisfy the
// repo formatter. Emitting unformatted code meant every `bun run generate` left
// `apps/site/src/generated/manifest.ts` dirty, which fails `bun run lint` in CI
// on a fresh checkout — the kind of gate failure that looks like someone broke
// something when nobody did. Format here, at the source, rather than relying on
// someone to remember to run `format` after generating.
try {
  const { execFileSync } = await import("node:child_process");
  execFileSync("npx", ["biome", "check", "--write", target], {
    stdio: "ignore",
  });
} catch {
  // Formatter unavailable (offline / no npx). The file is still written and
  // correct; only its formatting is not guaranteed, and `bun run lint` will say so.
  console.warn(
    "generate-manifest: could not run biome; run `bun run format` before lint",
  );
}

console.log(
  "generate-manifest: " +
    entries.length +
    " rows (web " +
    byPlatform.web.length +
    ", mobile " +
    byPlatform.mobile.length +
    ") -> " +
    target,
);
