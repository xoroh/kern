/**
 * generate-maturity.mjs — the site's copy of the maturity source.
 *
 * WHY A COPY AND NOT AN IMPORT
 * `packages/mcp/src/maturity.ts` is the single generated source of truth
 * (D-038), but `@xoroh/kern-mcp`'s `exports` map exposes only `.` and
 * `./manifest` and its build compiles only `src/index.ts` + `src/manifest.ts`
 * — so `@xoroh/kern-mcp/maturity` does not resolve at runtime or at type
 * level. Until that export lands, the site generates its own copy from the
 * SAME source file, which keeps the copy and the source regen-green together:
 * a re-run of the mcp generator followed by a re-run of this one cannot drift.
 *
 * This runs under `bun` (see package.json `generate`), which imports the TS
 * source directly — a real module load, not a text scrape.
 *
 * Rule honoured: nothing here invents a maturity value. Rows come verbatim
 * from the source; a name the source does not know produces no row, and the
 * page then renders no state chip at all rather than a guessed one.
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = join(HERE, "..");
const SOURCE = join(SITE, "..", "..", "packages", "mcp", "src", "maturity.ts");

const { MATURITY, MATURITY_BY_STATE } = await import(SOURCE);

const rows = MATURITY.map((r) => ({
  name: r.name,
  export: r.export,
  platform: r.platform,
  state: r.state,
  version: r.version,
}));

const banner = `// GENERATED by apps/site/scripts/generate-maturity.mjs — DO NOT EDIT.
// Source of truth: packages/mcp/src/maturity.ts (D-038).
// Regenerate: bun run generate

export type MaturityState = "Preview" | "Stable" | "Maintained" | "Sunsetting" | "Archived";

export type MaturityRow = {
  name: string;
  export: string;
  platform: "web" | "native";
  state: MaturityState;
  version: string;
};
`;

const body = `export const MATURITY: readonly MaturityRow[] = ${JSON.stringify(rows, null, 2)};

const BY_EXPORT = new Map<string, MaturityRow>();
const BY_EXPORT_PLATFORM = new Map<string, MaturityRow>();
for (const row of MATURITY) {
  BY_EXPORT.set(row.export, row);
  BY_EXPORT_PLATFORM.set(row.export + "::" + row.platform, row);
}

/** Maturity of a single export on a single renderer. */
export function maturityForExport(
  exportName: string,
  platform: "web" | "native",
): MaturityRow | undefined {
  return BY_EXPORT_PLATFORM.get(exportName + "::" + platform) ?? BY_EXPORT.get(exportName);
}

/**
 * The maturity a page may assert, given the exports it owns.
 *
 * Asserts a state only when EVERY owned export agrees — a page spanning a
 * Preview part and a Stable part has no single honest state, so it gets none
 * rather than a majority vote that would be a claim nothing backs.
 * Returns undefined when the source knows none of the names, so a stale page
 * renders no chip instead of inventing one.
 */
export function maturityForExports(
  exportNames: readonly string[],
  platform: "web" | "native",
): { state: MaturityState; version: string } | undefined {
  const rowsFor = exportNames
    .map((n) => maturityForExport(n, platform))
    .filter((r): r is MaturityRow => r !== undefined);
  if (rowsFor.length === 0) return undefined;
  const states = new Set(rowsFor.map((r) => r.state));
  const versions = new Set(rowsFor.map((r) => r.version));
  if (states.size !== 1 || versions.size !== 1) return undefined;
  return { state: rowsFor[0].state, version: rowsFor[0].version };
}

export const MATURITY_BY_STATE: Readonly<Record<MaturityState, readonly string[]>> = ${JSON.stringify(MATURITY_BY_STATE, null, 2)};
`;

const out = join(SITE, "src", "generated", "maturity.ts");
writeFileSync(out, `${banner}\n${body}`);

const byState = rows.reduce((acc, r) => {
  acc[r.state] = (acc[r.state] ?? 0) + 1;
  return acc;
}, {});
console.log(
  `generate-maturity: wrote ${rows.length} rows to src/generated/maturity.ts (${Object.entries(
    byState,
  )
    .map(([k, v]) => `${k}=${v}`)
    .join(" ")})`,
);
