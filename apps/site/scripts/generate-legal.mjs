/**
 * generate-legal.mjs — the licence facts, read from the LICENSE files.
 *
 * WHY GENERATED
 * §19 asks for a "which package, which license" table for the day packages
 * ever differ. A hand-typed table of seven MITs is correct today and a lie
 * the day one package relicenses — the M2 licence drift (footer claimed
 * Apache-2.0 while the repo was MIT) is exactly this class. Reading every
 * LICENSE file at generate time keeps the table and the footer honest
 * together: REPO_LICENSE already comes from the root LICENSE, and
 * PACKAGE_LICENSES extends the same fact to every package.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SITE = join(HERE, "..");
const ROOT = join(SITE, "..", "..");

/** Every licence-bearing unit: the repo root plus each published package. */
const UNITS = [
  { label: "kern (repository)", file: "LICENSE" },
  { label: "@xoroh/kern", file: "packages/kern/LICENSE" },
  { label: "@xoroh/kern-tokens", file: "packages/kern-tokens/LICENSE" },
  { label: "@xoroh/kern-native", file: "packages/kern-native/LICENSE" },
  { label: "@xoroh/kern-icons", file: "packages/kern-icons/LICENSE" },
  { label: "@xoroh/kern-primitives", file: "packages/kern-primitives/LICENSE" },
  { label: "@xoroh/kern-mcp", file: "packages/mcp/LICENSE" },
];

function shortName(firstLine) {
  return firstLine.replace(/\s+License\s*$/i, "").trim() || firstLine.trim();
}

const rows = UNITS.map(({ label, file }) => {
  const text = readFileSync(join(ROOT, file), "utf8");
  const first = text.split(/\r?\n/).find((l) => l.trim()) ?? "";
  return { label, file, license: shortName(first) };
});

const rootText = readFileSync(join(ROOT, "LICENSE"), "utf8");

// Biome formats generated output before writing (same rule as generate-props):
// the generator and the formatter agree instead of racing.
const { execFileSync } = await import("node:child_process");
const raw = `// GENERATED by apps/site/scripts/generate-legal.mjs — DO NOT EDIT.
// Source of truth: LICENSE + packages/*/LICENSE.
// Regenerate: bun run generate

export type LicenseRow = {
  /** Display name: the repo or the package. */
  label: string;
  /** Repo-relative path of the LICENSE file this row was read from. */
  file: string;
  /** Short name from the file's first line ("MIT License" -> "MIT"). */
  license: string;
};

export const PACKAGE_LICENSES: readonly LicenseRow[] = ${JSON.stringify(rows, null, 2)};

export const LICENSE_TEXT: string = ${JSON.stringify(rootText)};
`;
let formatted = raw;
try {
  formatted = execFileSync(
    join(ROOT, "node_modules", ".bin", "biome"),
    ["format", "--stdin-file-path=legal.ts"],
    { input: raw, encoding: "utf8", cwd: ROOT },
  );
} catch {
  // Biome unavailable: keep unformatted, never silently drop the export.
}
const out = join(SITE, "src", "generated", "legal.ts");
writeFileSync(out, formatted);

const distinct = [...new Set(rows.map((r) => r.license))];
console.log(
  `generate-legal: wrote ${rows.length} licence rows (${distinct.join(", ")})`,
);
