#!/usr/bin/env bun
/**
 * generate-a11y.mjs — per-page *.a11y.json axe expectations (Part 7).
 *
 * Reads (repo, read-only):  content docs (web/*.ts, mobile/*.ts via dynamic
 *   import — same discovery check-docs.mjs uses), demo registries
 *   (demos/web/registry.tsx, demos/mobile/registry.tsx), optional
 *   hand-authored overrides in src/a11y-overrides/<platform>/<slug>.json.
 * Writes: src/generated/a11y/<platform>/<slug>.a11y.json (canonical, the
 *   file reviewers read) + src/generated/a11y.ts (same objects as a TS
 *   barrel — tsc has no resolveJsonModule, so the page imports the barrel;
 *   both serializations come from one object, freshness-compared as a unit).
 *
 * One file per PAGE, expectations per DEMO (export): the registry maps
 * export -> demo, so the export is the demo unit. Exports with no live demo
 * get an entry with hasLiveDemo:false and no expectations — "nothing to run
 * axe against" is itself useful machine data.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { deriveExpectations } from "./a11y-derive.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");
const OUT_DIR = join(APP, "src", "generated", "a11y");
const OVERRIDES = join(APP, "src", "a11y-overrides");

const { WEB_DEMOS } = await import(
  join(APP, "src", "demos", "web", "registry.tsx")
);
const { MOBILE_DEMOS } = await import(
  join(APP, "src", "demos", "mobile", "registry.tsx")
);

const PLATFORMS = {
  web: { dir: join(APP, "src", "content", "web"), demos: WEB_DEMOS },
  mobile: { dir: join(APP, "src", "content", "mobile"), demos: MOBILE_DEMOS },
};

const NOTE =
  "Expectations, not measurements: no axe runner exists in this repo, so nothing here was observed in a browser. " +
  "derived = mechanical restatement of a claim the page already makes (basis names the source). " +
  "authored = new human judgment from src/a11y-overrides/. Run axe against the live demo to measure.";

let pages = 0;
let demos = 0;
const barrel = {};

for (const [platform, { dir, demos: registry }] of Object.entries(PLATFORMS)) {
  mkdirSync(join(OUT_DIR, platform), { recursive: true });
  const files = readdirSync(dir).filter((f) => f.endsWith(".ts"));
  for (const file of files.sort()) {
    const mod = await import(join(dir, file));
    for (const doc of Object.values(mod)) {
      if (
        !doc ||
        typeof doc !== "object" ||
        !doc.slug ||
        !Array.isArray(doc.parts)
      )
        continue;
      const entries = {};
      for (const exportName of doc.parts) {
        const hasLiveDemo = Boolean(registry[exportName]);
        entries[exportName] = {
          hasLiveDemo,
          expectations: deriveExpectations(doc, exportName, hasLiveDemo),
        };
        demos++;
      }
      // Hand-authored judgment merges here, stamped authored. The generator
      // never emits provenance:authored itself.
      const overridePath = join(OVERRIDES, platform, `${doc.slug}.json`);
      const overrideKeys = [];
      try {
        const overrides = JSON.parse(readFileSync(overridePath, "utf8"));
        for (const [exportName, extra] of Object.entries(overrides)) {
          if (!entries[exportName]) {
            console.error(
              `x    override for unknown part ${exportName} in ${platform}/${doc.slug}`,
            );
            process.exit(1);
          }
          for (const e of extra) {
            entries[exportName].expectations.push({
              ...e,
              provenance: "authored",
            });
          }
          overrideKeys.push(exportName);
        }
      } catch (err) {
        if (err.code !== "ENOENT") throw err;
      }
      const page = {
        page: `${platform}/${doc.slug}`,
        measured: false,
        note: NOTE,
        demos: entries,
      };
      writeFileSync(
        join(OUT_DIR, platform, `${doc.slug}.a11y.json`),
        JSON.stringify(page, null, 2) + "\n",
      );
      barrel[`${platform}/${doc.slug}`] = page;
      pages++;
    }
  }
}

const barrelSrc = `// GENERATED by apps/site/scripts/generate-a11y.mjs — do not hand-edit.
// Same objects as src/generated/a11y/*/*.a11y.json (canonical), as a TS
// barrel: tsc has no resolveJsonModule, so the component page imports this.
// Both serializations come from one object in the generator; the freshness
// gate compares both byte-for-byte, so they cannot drift apart.
export type A11yExpectation = {
  rule: string;
  expect: "pass" | "gap" | "fail";
  provenance: "derived" | "authored";
  basis: string;
};
export type A11yDemo = { hasLiveDemo: boolean; expectations: A11yExpectation[] };
export type A11yPage = {
  page: string;
  measured: false;
  note: string;
  demos: Record<string, A11yDemo>;
};
export const A11Y: Record<string, A11yPage> = ${JSON.stringify(barrel, null, 2)};
`;
writeFileSync(join(APP, "src", "generated", "a11y.ts"), barrelSrc);
console.log(`generate-a11y: wrote ${pages} pages, ${demos} demo entries`);
