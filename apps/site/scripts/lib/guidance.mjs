/**
 * The guidance corpus — the teaching half of every component page.
 *
 * ONE STANDARD (ADR-115): the component page carries the REFERENCE (props,
 * keyboard, ARIA, boundaries, customization); the GUIDANCE (features prose,
 * the Do/Don't pair, the token table, the anatomy, the deviations, the FAQ)
 * lives in `docs/m3-guidance/<family>.md`, one file per family, moved
 * verbatim from the pages on 2026-10-19.
 *
 * WHY A SHARED MODULE
 *
 * Three readers need the guidance, and they must not disagree:
 *
 *   1. `scripts/check-guidance.mjs` — the gate: re-renders every guidance
 *      file from `manifest.json` and compares it byte-for-byte, so a
 *      hand-edit to a guidance file is caught.
 *   2. `scripts/lib/page-md.mjs` — the machine surface: the per-page `.md`
 *      carries the family's guidance so an AI consumer reading the `.md` (or
 *      the MCP index that points at it) gets the teaching, not just the
 *      reference.
 *   3. `scripts/check-docs.mjs` — the reference gate: the deviations and the
 *      Do/Don't pair moved to the guidance file, so the rules that used to
 *      read `doc.deviations` read them from HERE.
 *
 * The RENDERER lives here too, and it is the same renderer the one-off
 * migration script (`scripts/migrate-guidance.mjs`) used to write the files:
 * one format, one implementation, so "the file on disk" and "a fresh render"
 * can be compared byte-for-byte instead of by eye.
 *
 * WHY THE MANIFEST IS THE SOURCE
 *
 * `manifest.json` holds the moved values VERBATIM, per family per platform.
 * It is what makes the move checkable after the fact: the gate re-renders
 * each guidance file from the manifest and compares, and every string the
 * manifest holds must appear in the file (the zero-lost-lines check). A
 * guidance file that drifts from the manifest is a lie about what was moved.
 */

import { existsSync, readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..", "..");
const ROOT = join(APP, "..", "..");

/** Where the guidance corpus lives (repo root, not the app). */
export const GUIDANCE_DIR = join(ROOT, "docs", "m3-guidance");
/** The manifest: the moved values, verbatim, per family per platform. */
export const MANIFEST_PATH = join(GUIDANCE_DIR, "manifest.json");

/**
 * The fields that MOVED from the page to the guidance file. A page that
 * still carries one of them is a page that says the same thing twice — and
 * the gate fails it, because the split is the point.
 */
export const MOVED_FIELDS = [
  "features",
  "usage",
  "tokens",
  "faq",
  "deviations",
  "anatomy",
];

/** The platform marker used in the guidance file. */
const PLATFORM = { web: "Web", mobile: "Native" };

/**
 * The header every guidance file carries. It is part of the rendered bytes:
 * a file without it is a hand-edit, and the byte comparison fails.
 */
const HEADER = `<!-- Generated by apps/site/scripts/one-off/migrate-guidance.mjs. Do not edit by hand.
     The component pages carry the reference; this file carries the guidance. -->`;

/**
 * The manifest, read once and cached. `null` when the corpus is missing —
 * the gate reports that as a missing corpus rather than crashing, because a
 * missing directory is a state to be named, not an exception to be thrown.
 */
let manifestCache = null;

export function loadManifest() {
  if (manifestCache) return manifestCache;
  if (!existsSync(MANIFEST_PATH)) return null;
  manifestCache = JSON.parse(readFileSync(MANIFEST_PATH, "utf8"));
  return manifestCache;
}

/**
 * The moved content for one family on one platform, or `null` when that
 * platform carried nothing (or the family is not in the manifest).
 */
export function guidanceFor(family, platform) {
  const manifest = loadManifest();
  if (!manifest) return null;
  return manifest[family]?.platforms?.[platform] ?? null;
}

/**
 * Every string the manifest holds for one entry, flattened. The zero-lost-
 * lines check walks this list and asserts each string appears in the
 * rendered guidance file — so a renderer that silently drops a field (a
 * table row, a Don't) is caught even when the file still looks plausible.
 */
export function manifestStrings(moved) {
  const out = [];
  if (!moved) return out;
  if (typeof moved.features === "string") out.push(moved.features);
  for (const line of moved.usage?.do ?? []) out.push(line);
  for (const line of moved.usage?.dont ?? []) out.push(line);
  for (const row of moved.tokens ?? [])
    out.push(row.element, row.state, row.token, row.value);
  for (const row of moved.anatomy ?? []) out.push(row.name, row.role);
  for (const row of moved.deviations ?? [])
    out.push(row.id, row.spec, row.kern, row.why);
  for (const row of moved.faq ?? []) out.push(row.q, row.a);
  return out.filter((s) => typeof s === "string" && s.length > 0);
}

function bullet(text) {
  return `- ${text}`;
}

function table(headers, rows) {
  return [
    `| ${headers.join(" | ")} |`,
    `| ${headers.map(() => "---").join(" | ")} |`,
    ...rows.map((r) => `| ${r.join(" | ")} |`),
  ].join("\n");
}

/**
 * One platform's section, rendered from the manifest's moved values.
 *
 * The subsection order is FIXED: features → usage → tokens → anatomy →
 * deviations → faq. It is the order a reader needs them (what it is, how to
 * use it, how it is themed, how it is put together, where it departs from
 * the spec, what people ask), and it is the order the migration wrote.
 */
export function renderPlatformSection(moved) {
  const lines = [];
  if (moved.features) lines.push("### Features", "", moved.features, "");
  if (moved.usage) {
    lines.push("### Usage", "");
    if (moved.usage.do?.length) {
      lines.push("**Do**", "", ...moved.usage.do.map(bullet), "");
    }
    if (moved.usage.dont?.length) {
      lines.push("**Don't**", "", ...moved.usage.dont.map(bullet), "");
    }
  }
  if (moved.tokens?.length) {
    lines.push(
      "### Tokens",
      "",
      table(
        ["Element", "State", "Token", "Value"],
        moved.tokens.map((t) => [t.element, t.state, t.token, t.value]),
      ),
      "",
    );
  }
  if (moved.anatomy?.length) {
    lines.push(
      "### Anatomy",
      "",
      table(
        ["Part", "Role"],
        moved.anatomy.map((a) => [a.name, a.role]),
      ),
      "",
    );
  }
  if (moved.deviations?.length) {
    lines.push(
      "### Deviations from Material 3",
      "",
      ...moved.deviations.flatMap((d) => [
        `**${d.id}** — spec: ${d.spec}`,
        "",
        `Kern: ${d.kern}`,
        "",
        `Why: ${d.why}`,
        "",
      ]),
    );
  }
  if (moved.faq?.length) {
    lines.push(
      "### FAQ",
      "",
      ...moved.faq.flatMap((f) => [`**${f.q}**`, "", f.a, ""]),
    );
  }
  return lines.join("\n").trim();
}

/**
 * The whole guidance file for one family, rendered from the manifest.
 *
 * Byte-identical to what the migration wrote: same header, same platform
 * order (web then native), same subsections, same trailing newline. That is
 * what lets the gate compare the file on disk to a fresh render and call a
 * difference a defect.
 */
export function renderGuidanceFile(familyName, platforms) {
  const out = [`# ${familyName} — M3 guidance`, "", HEADER, ""];
  for (const platform of ["web", "mobile"]) {
    const moved = platforms?.[platform];
    if (!moved) continue;
    const body = renderPlatformSection(moved);
    if (!body) continue;
    out.push(`## ${PLATFORM[platform]}`, "", body, "");
  }
  return `${out
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trimEnd()}\n`;
}
