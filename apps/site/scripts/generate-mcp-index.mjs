#!/usr/bin/env bun
/**
 * generate-mcp-index — public/mcp/index.json, the machine index of the docs
 * corpus for the MCP server (5D agent surfaces).
 *
 * One entry per docs page (every component family on web + mobile, every
 * foundations page) with the page route and its per-page .md URL, built from
 * the same content docs and foundations registry the pages and the .md
 * emission read — three single sources, no hand-listed pages. Served at
 * /mcp/index.json with the deployed site; the MCP server (or any agent)
 * fetches it over HTTP rather than scraping HTML.
 *
 * BUILD OUTPUT, not a committed artefact: public/mcp/ is gitignored and
 * regenerated by `bun run generate` (hence into the deployed bundle via
 * public/), the same arrangement as public/md/. The freshness contract lives
 * in check-mcp-index instead: it re-derives this same module and asserts
 * every docs page is indexed with its own one-liner and exact URLs.
 */
import { mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { FOUNDATIONS } from "../src/foundations/shell.tsx";
import { buildMcpIndex } from "./lib/mcp-index.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = join(HERE, "..");
const OUT = join(APP, "public", "mcp", "index.json");

async function loadDocs(subdir) {
  const dir = join(APP, "src", "content", subdir);
  const docs = [];
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".ts"))
    .sort()) {
    const mod = await import(join(dir, file));
    for (const doc of Object.values(mod)) {
      if (doc && typeof doc === "object" && doc.slug && doc.name)
        docs.push(doc);
    }
  }
  return docs;
}

const families = {
  web: await loadDocs("web"),
  mobile: await loadDocs("mobile"),
};
const index = buildMcpIndex(families, FOUNDATIONS);

mkdirSync(join(APP, "public", "mcp"), { recursive: true });
writeFileSync(OUT, `${JSON.stringify(index, null, 2)}\n`);
console.log(
  `generate-mcp-index: wrote ${index.count} page(s) to public/mcp/index.json`,
);
