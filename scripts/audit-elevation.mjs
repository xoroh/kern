#!/usr/bin/env node
/**
 * P2-2 — per-component resting-elevation audit, GENERATED.
 *
 * Produces `docs/elevation-audit.md`: one row per web concept, carrying the
 * measured elevation, the M3 resting level, and the classification.
 *
 * Why generated: an audit table maintained by hand drifts from the tree the
 * moment either side moves, and a stale audit is worse than none — it reads as
 * coverage. Every number here comes from `scripts/measure-elevation.mjs` and the
 * `KERN_ELEVATION_COMPONENTS` table, so re-running is the whole maintenance.
 *
 * The three classifications, and why the middle one is the only real gap:
 *
 *   ASSERTED   the component carries a token, M3 names a level, the gate covers it.
 *   ABSENT-0   M3 places the component at resting level 0, where `level0` is
 *              `shadow: none`. Carrying NO token is the CONFORMANT state. A token
 *              here would render nothing while making the table look busier.
 *   NO-SPEC    M3 specifies no resting level for it, so there is nothing to
 *              assert either way — a kern extension, a CSS-only wrapper, or a
 *              part of another component.
 *
 * Run: `bun scripts/audit-elevation.mjs`
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { KERN_ELEVATION_COMPONENTS } from "../packages/kern-m3/src/kern-elevation.ts";
import { classifyElevation } from "./lib/elevation-audit.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "docs/elevation-audit.md");

// --- the registry, parsed structurally (not by regex over the whole file) ----
const manifest = readFileSync(
  join(ROOT, "packages/mcp/src/manifest.ts"),
  "utf8",
);
const rows = [
  ...manifest.matchAll(
    /name:\s*"([^"]+)",\s*export:\s*"[^"]+",\s*platform:\s*"(web|native)",\s*entrypoint:\s*"[^"]+",\s*path:\s*"([^"]+)"/g,
  ),
].map((m) => ({ name: m[1], platform: m[2], path: m[3] }));
const webConcepts = [
  ...new Set(rows.filter((r) => r.platform === "web").map((r) => r.name)),
].sort();

// Consume the actual table: comments/formatting cannot change its meaning.
const table = KERN_ELEVATION_COMPONENTS;

// --- MEASURE, using the existing script (the gate's own instrument) ---------
const measured = new Map();
if (webConcepts.length) {
  const out = execFileSync(
    "bun",
    [join(ROOT, "scripts/measure-elevation.mjs"), "--json", ...webConcepts],
    { cwd: ROOT, encoding: "utf8" },
  );
  for (const measurement of JSON.parse(out)) {
    measured.set(measurement.name, measurement.tokenLevels);
  }
}

// --- classify ---------------------------------------------------------------
const audit = webConcepts.map((name) => {
  const spec = table[name] ?? null;
  const levels = measured.get(name) ?? [];
  const got = levels.length ? levels : null;
  const verdict = classifyElevation(spec, levels);
  return {
    name,
    measured: got ? got.join("/") : "—",
    spec: spec ? spec.variants.join("/") : "—",
    rows: spec ? spec.rows.join("; ") : "—",
    verdict,
  };
});

const counts = {};
for (const row of audit) {
  counts[row.verdict] = (counts[row.verdict] ?? 0) + 1;
}

const body = [
  "# Resting-elevation audit — every web concept",
  "",
  "**GENERATED by `scripts/audit-elevation.mjs` — do not edit by hand.** Re-run the script.",
  "",
  `Web concepts in the registry: **${audit.length}** (the ladder's "68 components" is stale).`,
  "",
  "| verdict | count | meaning |",
  "|---|---:|---|",
  `| ASSERTED | ${counts.ASSERTED ?? 0} | carries a token; M3 names a level; \`check:kern\` covers it |`,
  `| ABSENT-0 | ${counts["ABSENT-0"] ?? 0} | M3 puts it at resting level 0 — \`level0\` is \`shadow: none\`, so **no token is the conformant state** |`,
  `| GAP | ${counts.GAP ?? 0} | **M3 names a level but the component carries no token** — the only real defect class |`,
  `| NO-SPEC | ${counts["NO-SPEC"] ?? 0} | M3 specifies no resting level — kern extension, CSS wrapper, or sub-part |`,
  `| MISMATCH | ${counts.MISMATCH ?? 0} | carries a level M3 does not assign to it — an UNEARNED shadow; this fails the audit |`,
  "",
  "## Why ABSENT-0 is not a gap",
  "",
  "M3's resting-elevation table places these at level **0**, and `elevation-level0` is",
  "`shadow: none`. Writing a level-0 token into a component would add a declaration that renders",
  'nothing while making this table look fuller. The chips page is explicit: *"Chip elevation',
  'defaults to 0 but can be elevated if they need more visual separation."* Absence is the',
  "conformant state, and `check:kern` gates it that way — a row permitting 0 is checked for the",
  "**absence** of a token, so adding an unearned shadow fails.",
  "",
  "## Audit table",
  "",
  "| component | measured | M3 resting | M3 rows | verdict |",
  "|---|---|---|---|---|",
  ...audit.map(
    (r) =>
      `| \`${r.name}\` | ${r.measured} | ${r.spec} | ${r.rows} | ${r.verdict} |`,
  ),
  "",
].join("\n");

writeFileSync(OUT, body);
console.log(
  `elevation audit: ${audit.length} web concepts -> ${OUT}\n` +
    Object.entries(counts)
      .map(([k, v]) => `  ${k.padEnd(9)} ${v}`)
      .join("\n"),
);
// Both are real defects: GAP is "M3 names a level, nothing ships it"; MISMATCH
// is "a shadow M3 never assigned". ABSENT-0 and NO-SPEC are conformant, and
// ASSERTED is the pass. Mutation-proving showed a MISMATCH reporting EXIT 0
// while being detected — a table that finds the defect and then passes anyway is
// the "gate that passes because it did not look" shape.
if (counts.GAP || counts.MISMATCH) process.exitCode = 1;
