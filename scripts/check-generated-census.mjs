#!/usr/bin/env node
/**
 * check-generated-census — every GENERATED artifact in the tree must have a
 * generator entry, and every generator entry must point at a real file.
 *
 * ## WHAT IT EXISTS FOR
 *
 * `check-generated-freshness` proves the files it LISTS are fresh. It cannot
 * prove the LIST is complete, and the incompleteness is the whole defect. Three
 * of the four defects in the 23:38 batch were generated artifacts that no
 * freshness entry claimed:
 *
 *   docs/elevation-audit.md                  re-dirtied on every elevation
 *                                             change; the tree carried live drift
 *   apps/site/src/generated/maturity.ts      lint-red while committed, born red
 *   apps/site/src/generated/changelog.ts     lint-red while committed
 *
 * All three were found by a human noticing a dirty or red file. None was found
 * by a gate. This is the gate.
 *
 * ## HOW "GENERATED" IS DECIDED
 *
 * By the artifact's own header, not by a curated file list. A file is treated as
 * generated when its first lines carry a generation marker. That is the same
 * signal a contributor reads when deciding not to hand-edit something, so the
 * census and the contributor agree by construction — a curated list would be
 * complete only with respect to whoever last updated it, which is the defect.
 *
 * ## THE FAILURE MODES ARE SEPARATE ON PURPOSE
 *
 *   artifact with NO entry   -> nothing regenerates it, nothing compares it.
 *                               This is the 23:38 defect.
 *   entry with NO artifact   -> the registry names a path that does not exist.
 *                               Usually a rename that missed the list; it also
 *                               means the freshness gate is comparing less than
 *                               it claims to.
 *
 * A file may be exempt, with a stated reason. Exemptions are listed by name in
 * `EXEMPT` below, never by pattern, because a pattern exemption is a hole with
 * a plausible-looking name.
 *
 * Usage: `bun run check:generated:census`
 */
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { GENERATORS } from "./generated-artifacts.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Header markers. Matched against the first HEAD_LINES lines, case-insensitively.
 *
 * The signal is ATTRIBUTION — "GENERATED BY <something>" — and nothing else.
 * The first attempt of this gate matched a bare `\bGENERATED\b` or a bare
 * `DO NOT EDIT` and reported 24 false positives on a clean tree: hand-written
 * files whose PROSE mentions generation (`packages/kern-icons/tools/lib/emit.ts`
 * opens "Emits generated icon code…", `docs/adr/003` is titled "Generated
 * component inventory", `.githooks/pre-commit` says "a stale generated
 * artefact"). A gate that flags 24 hand-written files on its first run does not
 * get read twice.
 *
 * The narrow marker is also the more honest one: "GENERATED by X" is a claim
 * about provenance that a contributor can act on, and it is what every real
 * generator in this repo actually writes.
 */
const HEAD_LINES = 5;
const MARKERS = [
  // Covers "GENERATED by", "Generated by", "AUTO-GENERATED by" (the latter
  // contains the former), and the backticked/bolded variants.
  /\bGENERATED\s+by\b/i,
];

/**
 * Files that carry a generation marker and are deliberately NOT in the registry.
 * Each needs a reason that survives being read in six months.
 *
 * Listed by exact path, never by pattern: a pattern exemption is a hole with a
 * plausible-looking name, and it is how the previous list of six
 * `component-sources.ts` references became unmaintainable.
 */
const EXEMPT = new Map([
  [
    "apps/site/.gitignore",
    "Carries a generation marker only to EXPLAIN that routeTree.gen.ts is no " +
      "longer tracked. The marker is documentation about another file; this " +
      "file is not an artifact.",
  ],
]);

/** Every TRACKED file in the repo, repo-relative, POSIX-separated. */
function trackedFiles() {
  // `git ls-files` rather than a filesystem walk: the census is about what is
  // COMMITTED, and node_modules / dist / .tanstack would otherwise drown the
  // signal in thousands of files nobody reviews.
  const out = execFileSync("git", ["ls-files"], {
    cwd: ROOT,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  return out.split("\n").filter(Boolean);
}

/** Does this file open with a generation marker? */
function declaresGenerated(abs) {
  let head;
  try {
    head = readFileSync(abs, "utf8")
      .split("\n")
      .slice(0, HEAD_LINES)
      .join("\n");
  } catch {
    // Binary or unreadable: not a text artifact, and this gate is not the place
    // to decide what a binary is.
    return false;
  }
  return MARKERS.some((re) => re.test(head));
}

/**
 * Is `file` claimed by some generator's outputs? A path matches EXACTLY, or as
 * a PREFIX of a directory-valued output entry.
 */
function ownerOf(file) {
  for (const entry of GENERATORS) {
    for (const out of entry.outputs) {
      if (file === out) return entry;
      // A directory entry owns everything beneath it.
      const abs = join(ROOT, out);
      if (
        existsSync(abs) &&
        statSync(abs).isDirectory() &&
        file.startsWith(`${out}/`)
      ) {
        return entry;
      }
    }
  }
  return null;
}

const tracked = trackedFiles();

// --- 1. every generated artifact must be claimed ------------------------------
const unclaimed = [];
let declared = 0;
for (const file of tracked) {
  const abs = join(ROOT, file);
  if (!existsSync(abs) || !statSync(abs).isFile()) continue;
  if (!declaresGenerated(abs)) continue;
  declared += 1;
  if (EXEMPT.has(file)) continue;
  if (!ownerOf(file)) unclaimed.push(file);
}

// --- 2. every claimed output must exist ---------------------------------------
const dangling = [];
for (const entry of GENERATORS) {
  for (const out of entry.outputs) {
    if (!existsSync(join(ROOT, out))) dangling.push(`${entry.name} -> ${out}`);
  }
}

const totalArtifacts = GENERATORS.flatMap((g) => g.outputs).length;

if (unclaimed.length || dangling.length) {
  console.error("generated-artifact census FAILED:\n");
  for (const f of unclaimed) {
    console.error(
      `  - ${f} declares itself GENERATED but no entry in ` +
        `scripts/generated-artifacts.mjs claims it. Nothing regenerates it and ` +
        `nothing compares it, so a hand-edit is invisible. That is the defect ` +
        `this gate exists for. Add a generator entry (or an EXEMPT entry with a ` +
        `reason if it is not really an artifact).`,
    );
  }
  for (const d of dangling) {
    console.error(
      `  - ${d} — the registry names a path that does not exist. A generator ` +
        `rename that missed this list makes check:generated compare less than ` +
        `it claims to.`,
    );
  }
  console.error(
    `\n  ${tracked.length} tracked file(s) · ${declared} declaring themselves ` +
      `generated · ${declared - unclaimed.length} claimed · ` +
      `${totalArtifacts} generator output path(s)`,
  );
  process.exit(1);
}

console.log(
  `generated-artifact census passes: ${declared} tracked file(s) declare ` +
    `themselves generated and every one is claimed by an entry in ` +
    `scripts/generated-artifacts.mjs (${EXEMPT.size} exempt, each with a stated ` +
    `reason); ${GENERATORS.length} generators / ${totalArtifacts} output ` +
    `path(s), all present. Nothing generated is ungated.`,
);
