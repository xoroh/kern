// Generates src/styles.css — the compiled public stylesheet (KERN-033).
// Run from the repo root: bun packages/kern/scripts/gen-styles.mjs
//
// What it is: tokens.css (ordinary token CSS from @xoroh/kern-tokens) INLINED
// plus the component keyframes from src/theme.css, with the resolved import
// spelling — so a consumer installs the tarball, imports ONE file, and gets
// working styles with NO Tailwind scan of Kern's checkout, NO private
// `@source`, and NO font surprise beyond the documented Inter import (which
// stays first, where CSS requires @import to be).
//
// What it is NOT: compiled Tailwind utilities. Components are authored in
// Tailwind utilities; a consumer that wants utility classes uses the
// documented Tailwind adapter (`@xoroh/kern-tokens/tailwind` + scanning its
// OWN installed files) or compiled source CSS. This file never pretends
// utilities are included — its header says exactly what it carries.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("../../..", import.meta.url).pathname;
const TOKENS_CSS = join(ROOT, "packages/kern-tokens/src/tokens.css");
const THEME_CSS = join(ROOT, "packages/kern/src/theme.css");
const OUT = join(ROOT, "packages/kern/src/styles.css");

const tokensCss = readFileSync(TOKENS_CSS, "utf8");
const themeCss = readFileSync(THEME_CSS, "utf8");

// The theme file's first line must be the resolvable token import — the stale
// `@xoroh/kern-theme/theme` this replaces shipped a broken public subpath
// (D01). Fail here, not in a consumer's bundler.
const firstLine = themeCss.split("\n")[0].trim();
if (firstLine !== '@import "@xoroh/kern-tokens/theme";') {
  console.error(
    `gen-styles FAILED — src/theme.css must open with '@import "@xoroh/kern-tokens/theme";', found: ${firstLine}`,
  );
  process.exit(1);
}

// Inline the token CSS, then the keyframes (everything after the import
// line). The fontsource @import inside tokens.css stays first in the output,
// where CSS requires @import rules to be.
const keyframes = themeCss.split("\n").slice(1).join("\n").trim();

const out = `/* GENERATED by packages/kern/scripts/gen-styles.mjs — do not hand-edit.
 * The compiled public stylesheet: token CSS inlined plus component keyframes.
 * Import ONE file: \`@xoroh/kern/styles\`. No Tailwind scan of Kern's checkout
 * required. Tailwind utilities are NOT included — see the Tailwind adapter at
 * \`@xoroh/kern-tokens/tailwind\`. */
${tokensCss.trim()}
${keyframes}
`;

writeFileSync(OUT, out);
console.log("styles.css regenerated");
