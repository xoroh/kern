// Generates src/motion.css from the feedback timing spec.
// Run from the repo root: bun packages/kern-theme/scripts/gen-motion-css.mjs
// Deterministic: identical input always emits identical output.
import { spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { feedbackTiming } from "../src/feedback.ts";

const ROOT = new URL("../../..", import.meta.url).pathname;
const OUT = join(new URL("..", import.meta.url).pathname, "src/motion.css");

const [x1, y1, x2, y2] = feedbackTiming.easing;
const easing = `cubic-bezier(${x1}, ${y1}, ${x2}, ${y2})`;
const cycle = `${feedbackTiming.cycleMs}ms`;

const lines = [
  "/* Generated by scripts/gen-motion-css.mjs from the feedback timing spec. */",
  "",
  "@keyframes kern-loader-dot {",
  "  0%, 80%, 100% { opacity: 0.25; transform: scale(0.8); }",
  "  40% { opacity: 1; transform: scale(1); }",
  "}",
  "",
  "@keyframes kern-loader-bar {",
  "  0% { transform: translateX(-100%); }",
  "  100% { transform: translateX(400%); }",
  "}",
  "",
  "@keyframes kern-loader-shape {",
  "  0%, 100% { transform: translateY(0) scale(1); }",
  "  50% { transform: translateY(-12px) scale(1.05); }",
  "}",
  "",
  ".animate-kern-loader-dot {",
  `  animation: kern-loader-dot ${cycle} ${easing} infinite;`,
  "}",
  "",
  ".animate-kern-loader-bar {",
  `  animation: kern-loader-bar ${cycle} ${easing} infinite;`,
  "}",
  "",
  ".animate-kern-loader-shape {",
  `  animation: kern-loader-shape ${cycle} ${easing} infinite;`,
  "}",
];

writeFileSync(OUT, `${lines.join("\n").trimEnd()}\n`);
// Emit Biome-canonical formatting so `bun run lint` stays clean on regen.
const fmt = spawnSync(
  "bun",
  ["x", "@biomejs/biome", "format", "--write", OUT],
  { cwd: ROOT, stdio: "inherit" },
);
if (fmt.status !== 0) process.exit(fmt.status ?? 1);
console.log(`wrote ${OUT}`);
