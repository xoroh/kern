// Regenerates ../mcp/src/manifest.ts from the components directories.
// Run from the repo root: bun packages/mcp/scripts/generate-manifest.mjs
// A file counts as real when it contains no "not implemented yet" throw.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("../../..", import.meta.url).pathname;
const AREAS = [
  { dir: "packages/kern/src/react/components", platform: "web" },
  { dir: "packages/kern/src/react-native/components", platform: "native" },
];

function toExport(base) {
  return base
    .split("-")
    .map((p) => p[0].toUpperCase() + p.slice(1))
    .join("");
}

const entries = [];
for (const { dir, platform } of AREAS) {
  for (const file of readdirSync(join(ROOT, dir)).sort()) {
    if (!file.endsWith(".tsx") || file.endsWith(".test.tsx")) continue;
    const src = readFileSync(join(ROOT, dir, file), "utf8");
    const name = file.replace(/\.tsx$/, "");
    entries.push({
      name,
      export: toExport(name),
      platform,
      path: `src/${platform === "web" ? "react" : "react-native"}/components/${file}`,
      status: src.includes("not implemented yet") ? "stub" : "real",
    });
  }
}
// Native Button API lives in the entry point, not a component file.
entries.push({
  name: "button",
  export: "Button",
  platform: "native",
  path: "src/react-native/index.ts",
  status: "stub",
});

const out = `// GENERATED by scripts/generate-manifest.mjs — do not hand-edit.
export type ComponentStatus = "real" | "stub";

export type ComponentEntry = {
  name: string;
  export: string;
  platform: "web" | "native";
  path: string;
  status: ComponentStatus;
};

export const COMPONENTS: ComponentEntry[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(ROOT, "packages/mcp/src/manifest.ts"), `${out}\n`);
console.log(`wrote ${entries.length} entries`);
