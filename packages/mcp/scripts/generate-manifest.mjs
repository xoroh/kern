// Regenerates ../mcp/src/manifest.ts from the components directories.
// Run from the repo root: bun packages/mcp/scripts/generate-manifest.mjs
// A file counts as real when it contains no "not implemented yet" throw.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = new URL("../../..", import.meta.url).pathname;
const AREAS = [
  { dir: "packages/kern/src/react/components", platform: "web" },
  { dir: "packages/kern/src/react-native/components", platform: "native" },
];

const entries = [];
const toName = (exportName) =>
  exportName.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
for (const { dir, platform } of AREAS) {
  for (const file of readdirSync(join(ROOT, dir)).sort()) {
    if (!file.endsWith(".tsx") || file.endsWith(".test.tsx")) continue;
    const src = readFileSync(join(ROOT, dir, file), "utf8");
    const area = platform === "web" ? "react" : "react-native";
    const path = `src/${area}/components/${file}`;
    const status = src.includes("not implemented yet") ? "stub" : "real";
    // One entry per exported component (types, variant maps, style
    // functions excluded).
    for (const [, exportName] of src.matchAll(/export function (\w+)/g)) {
      if (exportName.endsWith("Styles")) continue;
      entries.push({
        name: toName(exportName),
        export: exportName,
        platform,
        path,
        status,
      });
    }
  }
}

// Native Button API lives in the entry point, not a component file.
const nativeIndex = readFileSync(
  join(ROOT, "packages/kern/src/react-native/index.ts"),
  "utf8",
);
entries.push({
  name: "button",
  export: "Button",
  platform: "native",
  path: "src/react-native/index.ts",
  status: nativeIndex.includes("not implemented yet") ? "stub" : "real",
});

const render = (e) =>
  `  {\n    name: "${e.name}",\n    export: "${e.export}",\n    platform: "${e.platform}",\n    path: "${e.path}",\n    status: "${e.status}",\n  },`;
const out = `// GENERATED by scripts/generate-manifest.mjs — do not hand-edit.
export type ComponentStatus = "real" | "stub";

export type ComponentEntry = {
  name: string;
  export: string;
  platform: "web" | "native";
  path: string;
  status: ComponentStatus;
};

export const COMPONENTS: ComponentEntry[] = [
${entries.map(render).join("\n")}
];
`;
writeFileSync(join(ROOT, "packages/mcp/src/manifest.ts"), out);
console.log(`wrote ${entries.length} entries`);
