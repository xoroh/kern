#!/usr/bin/env node
/**
 * generate-maturity — the ONE source the site's state chips read.
 *
 * WHY
 *
 * `apps/site/src/content/types.ts` declares `state?: string` on the content
 * shape and nothing ever populates it, so every maturity chip on the site
 * renders EMPTY. site-se was reading a field with no producer.
 *
 * The fix is not for the site to hold its own opinion, and not for a hand-typed
 * table that drifts. Maturity is a property of PACKAGE METADATA plus registry
 * status, so it is generated from both and published as one artefact.
 *
 * WHAT MATURITY IS DERIVED FROM, and why each input earns its place
 *
 *   version     Every package is currently 0.0.0 — nothing has been released
 *               under a semver contract yet. So the honest derived state is
 *               "Preview", for everything. That is a MEASURED answer, not a
 *               placeholder: the moment a package is bumped past 0.x this
 *               generator emits a different state with no code change.
 *   deprecated  An npm `deprecated` field maps directly to Sunsetting, and a
 *               package marked for removal maps to Archived. Neither exists
 *               today; both are wired so the states cannot be invented later
 *               without a rule.
 *   status      The registry's `real | stub`. A stub is not shipped, so it
 *               cannot be Stable regardless of version.
 *
 * A 0.0.0 package rendering every chip as "Preview" is the CORRECT output today.
 * A hand-written table would have said "Stable" and been wrong on the first
 * release.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

/** @xoroh/kern-tokens -> the package dir it comes from. */
const PLATFORM_PACKAGE = { web: "kern", native: "kern-native" };

const OUT = join(ROOT, "packages/mcp/src/maturity.ts");

/** The five states the site renders. */
const STATES = ["Preview", "Stable", "Maintained", "Sunsetting", "Archived"];

/**
 * Derive one state's maturity from its package metadata.
 * Exported shape is deliberately flat and stringly-typed: the site already
 * types `state?: string`, and widening that to a union would be a change to a
 * file site-se owns.
 */
function maturityFor(pkgJson) {
  const version = pkgJson.version ?? "0.0.0";
  const deprecated = Boolean(pkgJson.deprecated);

  let state;
  if (deprecated) {
    state = "Sunsetting";
  } else if (version === "0.0.0") {
    // Nothing has been released under a semver contract. "Preview" is the
    // honest description and it is derived, not assumed.
    state = "Preview";
  } else {
    const major = Number.parseInt(version.split(".")[0] ?? "0", 10);
    state = major >= 1 ? "Stable" : "Preview";
  }

  return { state, version };
}

const manifestSrc = readFileSync(
  join(ROOT, "packages/mcp/src/manifest.ts"),
  "utf8",
);

// Parse the manifest with a real parse, not a regex over generated source: the
// generated file's own shape is what we depend on, and a tolerant regex here is
// how a rename silently empties the chips again.
const entries = [];
for (const m of manifestSrc.matchAll(
  /name:\s*"([^"]+)",\s*\n\s*export:\s*"([^"]+)",\s*\n\s*platform:\s*"(web|native)",\s*\n\s*path:\s*"([^"]+)",\s*\n\s*status:\s*"(real|stub)",/g,
)) {
  entries.push({
    name: m[1],
    export: m[2],
    platform: m[3],
    status: m[5],
  });
}

if (entries.length === 0) {
  console.error(
    "generate-maturity FAILED: parsed 0 entries from the manifest. The entry " +
      "shape changed, so this generator would publish an empty maturity table " +
      "and every chip would go blank again -- the exact defect it exists to fix.",
  );
  process.exit(1);
}

// One version lookup per package, not per export.
const packageMeta = {};
for (const dir of new Set(Object.values(PLATFORM_PACKAGE))) {
  const pkgJson = JSON.parse(
    readFileSync(join(ROOT, "packages", dir, "package.json"), "utf8"),
  );
  packageMeta[dir] = maturityFor(pkgJson);
}

/** state -> export names, so the site can render a filter without scanning. */
const byState = Object.fromEntries(STATES.map((s) => [s, []]));

const rows = entries.map((e) => {
  const meta = packageMeta[PLATFORM_PACKAGE[e.platform]];
  // A stub is not shipped, so it cannot claim a released state.
  const state = e.status === "stub" ? "Preview" : meta.state;
  byState[state].push(e.name);
  return { name: e.name, export: e.export, platform: e.platform, state, version: meta.version };
});

for (const s of STATES) byState[s] = [...new Set(byState[s])].sort();

const out = `// GENERATED by packages/mcp/scripts/generate-maturity.mjs — do not hand-edit.
//
// The ONE source the site's maturity chips read. Derived from package metadata
// (version, deprecated) and registry status (real | stub) — never hand-typed,
// because a hand-typed table is a second opinion that drifts from the packages
// it describes.
//
// Today every package is 0.0.0, so every real export is "Preview". That is a
// measured result, not a placeholder: bump a package past 0.x and this file
// changes with no code edit.
export type MaturityState =
${STATES.map((s) => `  | "${s}"`).join("\n")};

export type MaturityRow = {
  name: string;
  export: string;
  platform: "web" | "native";
  state: MaturityState;
  version: string;
};

/** Every registry export, with its derived maturity. */
export const MATURITY: readonly MaturityRow[] = ${JSON.stringify(rows, null, 2)} as const;

/** Export names grouped by state, for the site's filter chips. */
export const MATURITY_BY_STATE: Readonly<Record<MaturityState, readonly string[]>> = ${JSON.stringify(byState, null, 2)} as const;

/**
 * Read one component's maturity. Returns undefined for a name the registry does
 * not know, so a stale content page renders nothing rather than claiming a state
 * for a component that does not exist.
 */
export function maturityFor(name: string): MaturityRow | undefined {
  return MATURITY.find((r) => r.name === name);
}
`;

writeFileSync(OUT, out);

const counts = STATES.map((s) => `${s}=${byState[s].length}`).join(" ");
console.log(`generate-maturity: wrote ${rows.length} rows to packages/mcp/src/maturity.ts`);
console.log(`  by state: ${counts}`);
